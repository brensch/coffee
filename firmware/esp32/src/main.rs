//! ESP32-C6 firmware (ESP32-C6-MINI-1U-H4: 4 MB flash, 105 C rated).
//!
//! This is the ESP32 shell around `coffee_node::Node`, the same node the PC binary
//! runs. All behaviour (engine, profiles, shot recording, API) lives there; the
//! pure timing, filtering and protocol pieces of this shell live in `coffee_board`
//! and are unit-tested on the host.
//!
//! # Machine mode (default)
//!
//! Two priorities, so networking can never starve the machine:
//!
//! - **Control** (`control.rs`, interrupt executor, high priority): crystal tick
//!   once per nominal mains cycle, ADC oversampling, switch debounce, engine tick,
//!   outputs, status LED, the 250 ms RTC watchdog. There is no zero-cross
//!   detector: the heater and pump SSRs are zero-cross and only ever switch at a crossing.
//! - **Everything else** (thread executor, preempted by control): Wi-Fi station
//!   with DHCP and reconnect (`net.rs`), the HTTP server (embedded UI, `/api/*`,
//!   `/api/ws` telemetry, `/api/ota`), the `coffee.local` mDNS responder, the USB
//!   console and log stream (`usb.rs`), and the flash write-back task (`store.rs`).
//!
//! The control task owns the node outright: no lock, so nothing on the network side
//! can make it wait. API requests reach it through a bounded queue that it drains
//! once per cycle, after outputs are applied, under a fixed budget; telemetry goes
//! the other way as a snapshot (`link.rs`). A stalled control task resets the chip
//! through the watchdog, and every output drops to off. Losing Wi-Fi changes
//! nothing: the physical brew and steam switches go straight to the engine.
//!
//! # Bridge mode (`--features bridge`)
//!
//! Hardware-in-the-loop: sensor frames arrive from `coffee-emu` over USB
//! (lockstep wire protocol) and actuator frames go back; the machine pins stay
//! off and there is no Wi-Fi (`bridge.rs`).
//!
//! # Pin map (controller v15, low voltage only)
//!
//! | Signal          | GPIO  | Notes                                                 |
//! |-----------------|-------|-------------------------------------------------------|
//! | Pressure        | 0     | ADC1_CH0, transducer through 10k/20k (x2/3)           |
//! | Boiler NTC      | 1     | ADC1_CH1 via 1k, 50k Molex NTC to GND, 4.7k 1 % to 3.3 V |
//! | 3.3 V sense     | 2     | ADC1_CH2, 10k/10k (x1/2): NTC reading made ratiometric |
//! | 5 V sense       | 3     | ADC1_CH3, 20k/10k (x1/3): pressure made ratiometric    |
//! | Valve           | 18    | push-pull, HIGH = on: AO3400A sinks the relay module (J8) |
//! | Pump            | 19    | push-pull, HIGH = on: AO3400A sinks the zero-cross SSR (J3) |
//! | Heater          | 20    | push-pull, HIGH = on: AO3400A sinks the zero-cross SSR (J2) |
//! | Brew switch     | 6     | dry contact to GND, 4.7k pull-up + 1k series, low = closed |
//! | Steam switch    | 7     | dry contact to GND, 4.7k pull-up + 1k series, low = closed |
//! | Status LED      | 23    | heartbeat heating, solid ready, fast blink fault      |
//! | Power switch    | 14    | dry contact to GND (J7.1); open = standby             |
//! | Panel LEDs      | 21/22/16 | power / coffee / steam lamps (J7.5-7), 330R, high = on |
//! | Scale SCK       | 17    | dual HX711 clock (J10.4), 100R, 10k pull-down          |
//! | Scale DOUT1/2   | 4/5   | HX711 data (J10.5/6); straps only SDIO edges         |
//! | USB D- / D+     | 12/13 | native USB Serial/JTAG (flashing, console, log)       |
//!
//! Strapping pins 8 and 9: GPIO8 has its external pull-up, GPIO9 is the BOOT pad. GPIO4/5
//! (MTMS/MTDI) strap only the SDIO clock edges, so they read the scale. GPIO15 is unused.

