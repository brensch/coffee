#[cfg(not(feature = "bridge"))]
mod machine {
    use crate::{control, net, store, usb};
    use coffee_node::{Node, NodeOptions};
    use embassy_executor::Spawner;
    use esp_hal::clock::CpuClock;
    use esp_hal::interrupt::Priority;
    use esp_hal::timer::timg::TimerGroup;
    use esp_rtos::embassy::InterruptExecutor;
    use static_cell::StaticCell;

    #[esp_hal::main]
    async fn main(spawner: Spawner) -> ! {
        let p = esp_hal::init(esp_hal::Config::default().with_cpu_clock(CpuClock::max()));
        esp_alloc::heap_allocator!(#[esp_hal::ram(reclaimed)] size: 64 * 1024);
        esp_alloc::heap_allocator!(size: 176 * 1024);

        let timg0 = TimerGroup::new(p.TIMG0);
        esp_rtos::start(timg0.timer0, p.FROM_CPU_INTR0);

        // Flash: partition table -> key/value store (config, profiles, shots, Wi-Fi).
        let kv = store::init(p.FLASH);

        let node = Node::new(
            coffee_board::KvStorage(kv),
            NodeOptions {
                info: crate::info(),
                max_shots: 20, // compressed, ~2.6 KB each
                persist_shots: true,
                history_capacity: 1200, // 4 min at 5 Hz, 29 KB
                history_hz: 5.0,
            },
        );

        // Control first, at high priority: outputs are driven low before anything else runs.
        // The node moves into the control task; nothing else holds it.
        static EXEC: StaticCell<InterruptExecutor<1>> = StaticCell::new();
        let exec = EXEC.init(InterruptExecutor::new(p.FROM_CPU_INTR1));
        let hi = exec.start(Priority::Priority2);
        hi.spawn(
            control::run(
                control::Pins {
                    rtc: p.RTC_TIMER,
                    adc1: p.ADC1,
                    pressure: p.GPIO0,
                    ntc: p.GPIO1,
                    v3_sense: p.GPIO2,
                    v5_sense: p.GPIO3,
                    valve: p.GPIO18,
                    pump: p.GPIO19,
                    heater: p.GPIO20,
                    brew: p.GPIO6,
                    steam: p.GPIO7,
                    led: p.GPIO16,
                    power: p.GPIO14,
                    led_power: p.GPIO21,
                    led_coffee: p.GPIO22,
                    led_steam: p.GPIO23,
                    scale_sck: p.GPIO17,
                    scale_dout1: p.GPIO4,
                    scale_dout2: p.GPIO5,
                },
                node,
            )
            .unwrap(),
        );

        spawner.spawn(usb::run(p.USB_DEVICE).unwrap());
        spawner.spawn(store::flusher().unwrap());
        net::start(spawner, p.WIFI).await;

        loop {
            embassy_time::Timer::after_secs(3600).await;
        }
    }
}
