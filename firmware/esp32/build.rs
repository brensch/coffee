//! Embed the web UI: every file in `ui/dist` (built with `trunk build --release`)
//! is gzipped at build time and compiled into the image, so the board serves the
//! same UI as the PC engine with no filesystem. If the UI isn't built, a small
//! placeholder page is embedded instead (the API still works).

use std::{env, fs, io::Write, path::Path};

fn main() {
    let out = env::var("OUT_DIR").unwrap();
    let dist = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../ui/dist");
    println!("cargo:rerun-if-changed={}", dist.display());
    let mut files: Vec<(String, Vec<u8>)> = Vec::new();
    if let Ok(rd) = fs::read_dir(&dist) {
        for e in rd.flatten() {
            let p = e.path();
            if p.is_file() {
                println!("cargo:rerun-if-changed={}", p.display());
                files.push((format!("/{}", e.file_name().to_string_lossy()), fs::read(&p).unwrap()));
            }
        }
    }
    if !files.iter().any(|(n, _)| n == "/index.html") {
        files.push((
            "/index.html".into(),
            b"<!doctype html><title>coffee</title><body style='font-family:system-ui;padding:2rem'>\
              <h1>coffee</h1><p>The UI wasn't built into this firmware (run <code>trunk build --release</code> \
              in <code>ui/</code> and reflash). The API is at <a href='/api/status'>/api/status</a>.</p>"
                .to_vec(),
        ));
    }
    files.sort();
    let mut src = String::from("/// Gzipped UI files, generated by build.rs from ui/dist.\npub static ASSETS: &[(&str, &[u8])] = &[\n");
    let mut total = 0usize;
    for (i, (name, data)) in files.iter().enumerate() {
        let mut gz = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::best());
        gz.write_all(data).unwrap();
        let gz = gz.finish().unwrap();
        total += gz.len();
        let f = Path::new(&out).join(format!("ui{i}.gz"));
        fs::write(&f, &gz).unwrap();
        src.push_str(&format!("    ({name:?}, include_bytes!({:?})),\n", f.display().to_string()));
    }
    src.push_str("];\n");
    src.push_str(&format!("/// Total gzipped bytes.\npub const ASSETS_BYTES: usize = {total};\n"));
    fs::write(Path::new(&out).join("ui_assets.rs"), src).unwrap();
}
